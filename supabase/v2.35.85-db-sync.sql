CREATE OR REPLACE FUNCTION public.room_operating_window(p_room uuid, p_day date)
 RETURNS TABLE(is_open boolean, start_time time without time zone, end_time time without time zone, source text)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare r public.rooms; s public.app_settings; dow int;
begin
  select * into r from public.rooms where id=p_room;
  select * into s from public.app_settings where id=1;
  if r.id is null then is_open:=false;start_time:=null;end_time:=null;source:='missing';return next;return; end if;
  dow:=extract(isodow from p_day)::int;
  if r.operating_override then
    source:='room';
    if dow between 1 and 5 then is_open:=r.operating_weekday_enabled;start_time:=r.operating_weekday_start;end_time:=r.operating_weekday_end;
    elsif dow=6 then is_open:=r.operating_saturday_enabled;start_time:=r.operating_saturday_start;end_time:=r.operating_saturday_end;
    else is_open:=r.operating_sunday_enabled;start_time:=r.operating_sunday_start;end_time:=r.operating_sunday_end; end if;
  else
    source:='hospital';
    if dow between 1 and 5 then is_open:=s.operating_weekday_enabled;start_time:=s.operating_weekday_start;end_time:=s.operating_weekday_end;
    elsif dow=6 then is_open:=s.operating_saturday_enabled;start_time:=s.operating_saturday_start;end_time:=s.operating_saturday_end;
    else is_open:=s.operating_sunday_enabled;start_time:=s.operating_sunday_start;end_time:=s.operating_sunday_end; end if;
  end if;
  if not coalesce(is_open,false) or start_time is null or end_time is null or end_time<=start_time then is_open:=false; end if;
  return next;
end $function$;
CREATE OR REPLACE FUNCTION public.room_operating_status(p_room uuid, p_at timestamp with time zone DEFAULT clock_timestamp())
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  s public.app_settings; d date; lt time; w record; i int; nd date; nw record;
  active boolean:=false; nxt timestamptz; reason text:='closed'; src text:='hospital';
begin
  select * into s from public.app_settings where id=1;
  d:=(p_at at time zone 'Asia/Seoul')::date; lt:=(p_at at time zone 'Asia/Seoul')::time;
  select * into w from public.room_operating_window(p_room,d); src:=coalesce(w.source,'hospital');
  if s.early_closed_date=d then
    active:=false;reason:='early_closed';
  elsif w.is_open and lt>=w.start_time and lt<w.end_time then
    active:=true;reason:='open';nxt:=((d+w.end_time)::timestamp at time zone 'Asia/Seoul');
  elsif w.is_open and lt<w.start_time then
    active:=false;reason:='before_open';nxt:=((d+w.start_time)::timestamp at time zone 'Asia/Seoul');
  else
    active:=false;reason:='after_close';
  end if;
  if not active and nxt is null then
    for i in 1..8 loop
      nd:=d+i;
      select * into nw from public.room_operating_window(p_room,nd);
      if nw.is_open then nxt:=((nd+nw.start_time)::timestamp at time zone 'Asia/Seoul'); exit; end if;
    end loop;
  end if;
  return jsonb_build_object('active',active,'reason',reason,'source',src,'date',d,'start_time',w.start_time,'end_time',w.end_time,'next_transition_at',nxt,'early_closed',s.early_closed_date=d);
end $function$;
CREATE OR REPLACE FUNCTION public.player_get_state_operating(p_key uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare s jsonb; gate jsonb; rid uuid; current_next timestamptz; gate_next timestamptz; final_next timestamptz;
begin
  s:=public.player_get_state(p_key); if s is null then return null; end if;
  rid:=nullif(s#>>'{room,id}','')::uuid;
  gate:=public.room_operating_status(rid,clock_timestamp());
  current_next:=nullif(s->>'next_transition_at','')::timestamptz;
  gate_next:=nullif(gate->>'next_transition_at','')::timestamptz;
  if current_next is null then final_next:=gate_next; elsif gate_next is null then final_next:=current_next; else final_next:=least(current_next,gate_next); end if;
  if not coalesce((gate->>'active')::boolean,false) then
    return s || jsonb_build_object('mode','closed','playlist','[]'::jsonb,'notice_text',null,'session_expires_at',null,'next_transition_at',gate_next,'operating',gate,'sync_revision',coalesce(s->>'sync_revision','0')||':closed:'||coalesce(gate->>'date',''));
  end if;
  return s || jsonb_build_object('next_transition_at',final_next,'operating',gate);
end $function$;
CREATE OR REPLACE FUNCTION public.player_live_ping(p_key uuid, p_status jsonb)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_room uuid; v_now timestamptz:=clock_timestamp(); clean jsonb;
begin
  select id into v_room from public.rooms where player_key=p_key;
  if v_room is null then return; end if;
  if p_status is null or jsonb_typeof(p_status)<>'object' or pg_column_size(p_status)>16384 then return; end if;
  clean=jsonb_build_object(
    'video_id',case when jsonb_typeof(p_status->'video_id')='string' then left(p_status->>'video_id',64) else null end,
    'title',left(coalesce(p_status->>'title',''),160),'mode',left(coalesce(p_status->>'mode',''),32),
    'playback_state',left(coalesce(p_status->>'playback_state',''),32),
    'current_time',case when jsonb_typeof(p_status->'current_time')='number' then greatest(0,least((p_status->>'current_time')::numeric,86400)) else 0 end,
    'duration',case when jsonb_typeof(p_status->'duration')='number' then greatest(0,least((p_status->>'duration')::numeric,86400)) else 0 end,
    'muted',case when jsonb_typeof(p_status->'muted')='boolean' then (p_status->>'muted')::boolean else false end,
    'volume',case when jsonb_typeof(p_status->'volume')='number' then greatest(0,least((p_status->>'volume')::int,100)) else 0 end,
    'online',case when jsonb_typeof(p_status->'online')='boolean' then (p_status->>'online')::boolean else false end,
    'error',left(coalesce(p_status->>'error',''),300),'source',left(coalesce(p_status->>'source',''),64),
    'recovery_stage',case when jsonb_typeof(p_status->'recovery_stage')='number' then greatest(0,least((p_status->>'recovery_stage')::int,5)) else 0 end,
    'playlist_video_ids',coalesce((select jsonb_agg(left(x.value,64) order by x.ord) from jsonb_array_elements_text(case when jsonb_typeof(p_status->'playlist_video_ids')='array' then p_status->'playlist_video_ids' else '[]'::jsonb end) with ordinality as x(value,ord) where x.ord<=20),'[]'::jsonb),
    'playlist_titles',coalesce((select jsonb_agg(left(x.value,120) order by x.ord) from jsonb_array_elements_text(case when jsonb_typeof(p_status->'playlist_titles')='array' then p_status->'playlist_titles' else '[]'::jsonb end) with ordinality as x(value,ord) where x.ord<=8),'[]'::jsonb),
    'playlist_count',case when jsonb_typeof(p_status->'playlist_count')='number' then greatest(0,least((p_status->>'playlist_count')::int,500)) else 0 end,
    'current_index',case when jsonb_typeof(p_status->'current_index')='number' then greatest(0,least((p_status->>'current_index')::int,499)) else 0 end,
    'next_title',left(coalesce(p_status->>'next_title',''),160),'app_version',left(coalesce(p_status->>'app_version',''),24),'reported_at',left(coalesce(p_status->>'reported_at',''),48)
  );
  insert into public.player_live_status(room_id,last_seen_at,player_status,updated_at)
  values(v_room,v_now,clean,v_now)
  on conflict(room_id) do update set last_seen_at=excluded.last_seen_at,player_status=excluded.player_status,updated_at=excluded.updated_at;
end $function$;
CREATE OR REPLACE FUNCTION public.prune_player_events(p_keep_days integer DEFAULT 30)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE n bigint;
BEGIN
  DELETE FROM public.player_events WHERE occurred_at < now() - make_interval(days=>greatest(coalesce(p_keep_days,30),7));
  GET DIAGNOSTICS n=ROW_COUNT;
  RETURN n;
END $function$;
CREATE OR REPLACE FUNCTION public.enqueue_media_gc()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  IF TG_OP='DELETE' THEN
    IF OLD.source='r2' AND nullif(OLD.storage_path,'') IS NOT NULL THEN
      INSERT INTO public.media_gc_queue(site_id,storage_path,reason)
      VALUES(OLD.site_id,OLD.storage_path,'video_deleted')
      ON CONFLICT (storage_path) WHERE deleted_at IS NULL DO NOTHING;
    END IF;
    RETURN OLD;
  END IF;
  IF OLD.source='r2' AND nullif(OLD.storage_path,'') IS NOT NULL
     AND NEW.storage_path IS DISTINCT FROM OLD.storage_path THEN
    INSERT INTO public.media_gc_queue(site_id,storage_path,reason)
    VALUES(OLD.site_id,OLD.storage_path,'file_replaced')
    ON CONFLICT (storage_path) WHERE deleted_at IS NULL DO NOTHING;
  END IF;
  RETURN NEW;
END $function$;

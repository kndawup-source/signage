CREATE OR REPLACE FUNCTION public.player_get_state_lite(p_key uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE s jsonb; v_pl jsonb;
BEGIN
  s := public.player_get_state(p_key);
  IF s IS NULL THEN RETURN NULL; END IF;
  SELECT coalesce(jsonb_agg(
    (x.e - 'thumbnail') ||
    CASE WHEN jsonb_typeof(v.variants)='object' THEN jsonb_build_object('variants',v.variants) ELSE '{}'::jsonb END ||
    CASE WHEN v.sha256 IS NOT NULL THEN jsonb_build_object('sha256',v.sha256) ELSE '{}'::jsonb END ||
    CASE WHEN v.file_modified_at IS NOT NULL THEN jsonb_build_object('file_modified_at',v.file_modified_at) ELSE '{}'::jsonb END
    ORDER BY x.o), '[]'::jsonb)
  INTO v_pl
  FROM jsonb_array_elements(CASE WHEN jsonb_typeof(s->'playlist')='array' THEN s->'playlist' ELSE '[]'::jsonb END)
       WITH ORDINALITY AS x(e,o)
  LEFT JOIN public.videos v ON v.id=CASE
    WHEN (x.e->>'id') ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
    THEN (x.e->>'id')::uuid ELSE NULL END;
  RETURN s || jsonb_build_object(
    'playlist',v_pl,
    -- Include order, mode, URL, size, file modified time, digest.
    'playlist_hash',md5(jsonb_build_object(
      'mode',coalesce(s->>'mode',''),
      'playlist',(SELECT coalesce(jsonb_agg(jsonb_build_array(
        e->>'id',e->>'url',e->>'size',e->>'file_modified_at',e->>'sha256') ORDER BY o),'[]'::jsonb)
        FROM jsonb_array_elements(v_pl) WITH ORDINALITY AS y(e,o))
    )::text),
    'emergency_video',CASE WHEN jsonb_typeof(s->'emergency_video')='object'
      THEN (s->'emergency_video') - 'thumbnail'::text ELSE coalesce(s->'emergency_video','null'::jsonb) END
  );
END $function$;

CREATE OR REPLACE FUNCTION public.hospital_remove_room_manual_video(p_site uuid, p_room uuid, p_video uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_room public.rooms;
  v_remaining uuid[];
BEGIN
  IF NOT public.is_member() OR NOT public.staff_can_remote_control_room(p_room) THEN
    RAISE EXCEPTION 'not allowed' USING ERRCODE='42501';
  END IF;
  -- Explicit tenant scoping, including superadmin sessions in a selected hospital.
  SELECT * INTO v_room FROM public.rooms
  WHERE id=p_room AND site_id=p_site FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'TV not found in selected hospital' USING ERRCODE='22023'; END IF;
  IF NOT COALESCE(v_room.manual_active,false) OR NOT p_video=ANY(COALESCE(v_room.manual_video_ids,'{}'::uuid[])) THEN
    RAISE EXCEPTION 'video not in current manual TV list' USING ERRCODE='22023';
  END IF;
  v_remaining:=array_remove(v_room.manual_video_ids,p_video);
  UPDATE public.rooms SET
    manual_video_ids=COALESCE(v_remaining,'{}'::uuid[]),
    manual_active=COALESCE(array_length(v_remaining,1),0)>0,
    manual_starts_at=CASE WHEN COALESCE(array_length(v_remaining,1),0)>0 THEN manual_starts_at ELSE NULL END,
    manual_ends_at=CASE WHEN COALESCE(array_length(v_remaining,1),0)>0 THEN manual_ends_at ELSE NULL END,
    manual_updated_at=clock_timestamp()
  WHERE id=p_room AND site_id=p_site;
END;
$function$;
CREATE OR REPLACE FUNCTION public.hospital_reorder_floor_displays(p_site uuid, p_room_ids uuid[])
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_total integer := coalesce(array_length(p_room_ids,1),0);
  v_group uuid;
  v_group_count integer;
  v_existing_count integer;
begin
  if p_site is null or not public.can_manage_site(p_site) then
    raise exception '이 병원의 TV 순서를 변경할 권한이 없습니다.';
  end if;
  if v_total < 1 or v_total > 500 then
    raise exception 'TV 목록이 올바르지 않습니다.';
  end if;
  if (select count(distinct x.id) from unnest(p_room_ids) as x(id)) <> v_total then
    raise exception '중복된 TV가 포함되어 있습니다.';
  end if;
  -- Serialize concurrent reorder operations within one site; prevent stale partial lists.
  perform 1 from public.sites s where s.id=p_site for update;
  perform 1 from public.rooms r where r.site_id=p_site and r.id=any(p_room_ids) order by r.id for update;
  select (array_agg(distinct r.group_id))[1],count(distinct r.group_id),count(*)
    into v_group,v_group_count,v_existing_count
    from public.rooms r
    join public.signage_groups g on g.id=r.group_id and g.site_id=p_site
   where r.site_id=p_site and r.id=any(p_room_ids) and g.kind='floor';
  if v_existing_count <> v_total or v_group_count <> 1 or v_group is null then
    raise exception 'TV 목록에 다른 병원 또는 다른 층이 포함되어 있습니다.';
  end if;
  if (select count(*) from public.rooms where site_id=p_site and group_id=v_group) <> v_total then
    raise exception 'TV 목록이 변경되었습니다. 새로고침 후 다시 시도하세요.';
  end if;
  update public.rooms r set sort_order=(o.ord::integer*10)
  from unnest(p_room_ids) with ordinality as o(id,ord)
  where r.id=o.id and r.site_id=p_site and r.group_id=v_group;
end;
$function$;

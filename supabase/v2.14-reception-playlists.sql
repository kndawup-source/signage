-- Clinic Signage v2.14 — Reception workflow + real playlists
-- Safe to run repeatedly on the existing v2.13 database.

create table if not exists public.playlists (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  kind text not null default 'default' check(kind in ('default','patient')),
  target_age text[] not null default '{}',
  target_gender text[] not null default '{}',
  target_treatment text[] not null default '{}',
  active boolean not null default true,
  sort_order int not null default 0,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp()
);
create unique index if not exists playlists_name_uidx on public.playlists(lower(name));
create index if not exists playlists_target_treatment_idx on public.playlists using gin(target_treatment);

create table if not exists public.playlist_items (
  playlist_id uuid not null references public.playlists(id) on delete cascade,
  video_id uuid not null references public.videos(id) on delete cascade,
  sort_order int not null default 0,
  created_at timestamptz not null default clock_timestamp(),
  primary key(playlist_id,video_id)
);
create index if not exists playlist_items_order_idx on public.playlist_items(playlist_id,sort_order,created_at);

alter table public.rooms add column if not exists default_playlist_id uuid references public.playlists(id) on delete set null;

create table if not exists public.patient_sessions (
  id uuid primary key default gen_random_uuid(),
  queue_no bigint generated by default as identity,
  label text,
  age_group text,
  gender text,
  treatment text not null,
  status text not null default 'waiting' check(status in ('waiting','assigned','in_progress','completed','cancelled')),
  room_id uuid references public.rooms(id) on delete set null,
  waiting_started_at timestamptz not null default clock_timestamp(),
  assigned_at timestamptz,
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp()
);
create index if not exists patient_sessions_status_idx on public.patient_sessions(status,waiting_started_at);
create index if not exists patient_sessions_room_active_idx on public.patient_sessions(room_id) where status in ('assigned','in_progress');

alter table public.playlists enable row level security;
alter table public.playlist_items enable row level security;
alter table public.patient_sessions enable row level security;
drop policy if exists playlists_select on public.playlists;
create policy playlists_select on public.playlists for select to anon,authenticated using(public.is_member());
drop policy if exists playlists_admin on public.playlists;
create policy playlists_admin on public.playlists for all to anon,authenticated using(public.is_admin()) with check(public.is_admin());
drop policy if exists playlist_items_select on public.playlist_items;
create policy playlist_items_select on public.playlist_items for select to anon,authenticated using(public.is_member());
drop policy if exists playlist_items_admin on public.playlist_items;
create policy playlist_items_admin on public.playlist_items for all to anon,authenticated using(public.is_admin()) with check(public.is_admin());
grant select,insert,update,delete on public.playlists,public.playlist_items,public.patient_sessions to anon,authenticated;

-- Migrate the existing '기본' tagged videos once into a real default playlist.
do $$
declare v_playlist uuid;
begin
  select id into v_playlist from public.playlists where lower(name)=lower('기본') limit 1;
  if v_playlist is null then
    insert into public.playlists(name,kind,sort_order) values('기본','default',0) returning id into v_playlist;
  end if;
  insert into public.playlist_items(playlist_id,video_id,sort_order)
  select v_playlist,v.id,row_number() over(order by v.sort_order,v.created_at)::int*10
  from public.videos v where '기본'=any(coalesce(v.tags,'{}'::text[]))
  on conflict(playlist_id,video_id) do nothing;
  update public.rooms set default_playlist_id=v_playlist where default_playlist_id is null;
end $$;

create or replace function public.staff_create_patient(p_label text,p_age_group text,p_gender text,p_treatment text)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_id uuid; v_queue bigint;
begin
  if not public.is_member() then raise exception 'not allowed'; end if;
  if nullif(trim(coalesce(p_treatment,'')),'') is null then raise exception '진료유형을 선택하세요'; end if;
  insert into public.patient_sessions(label,age_group,gender,treatment)
  values(nullif(trim(coalesce(p_label,'')),''),nullif(trim(coalesce(p_age_group,'')),''),nullif(trim(coalesce(p_gender,'')),''),case when p_treatment='veneer' then 'minish' else p_treatment end)
  returning id,queue_no into v_id,v_queue;
  update public.patient_sessions set label=coalesce(label,'대기 '||lpad(v_queue::text,3,'0')) where id=v_id;
  return v_id;
end $$;

create or replace function public.staff_assign_patient(p_patient uuid,p_room uuid)
returns void language plpgsql security definer set search_path=public as $$
declare p public.patient_sessions; old_room uuid; v_mode text;
begin
  if not public.is_member() then raise exception 'not allowed'; end if;
  select * into p from public.patient_sessions where id=p_patient and status in ('waiting','assigned','in_progress') for update;
  if not found then raise exception '환자를 찾을 수 없습니다'; end if;
  select room_mode into v_mode from public.rooms where id=p_room;
  if v_mode not in ('treatment','consultation') then raise exception '환자 배정이 가능한 공간이 아닙니다'; end if;
  if exists(select 1 from public.patient_sessions x where x.room_id=p_room and x.status in ('assigned','in_progress') and x.id<>p_patient) then raise exception '이미 다른 환자가 배정된 공간입니다'; end if;
  old_room:=p.room_id;
  if old_room is not null and old_room<>p_room then
    update public.rooms set session_tags='{}',session_started_at=null,session_age_group=null,session_gender=null,session_treatment=null where id=old_room;
  end if;
  update public.patient_sessions set room_id=p_room,status='assigned',assigned_at=clock_timestamp(),started_at=null,updated_at=clock_timestamp() where id=p_patient;
  update public.rooms set session_age_group=p.age_group,session_gender=p.gender,session_treatment=p.treatment,session_tags=array_remove(array[p.age_group,p.gender,p.treatment]::text[],null),session_started_at=clock_timestamp() where id=p_room;
end $$;

create or replace function public.staff_start_patient(p_patient uuid)
returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_member() then raise exception 'not allowed'; end if;
  update public.patient_sessions set status='in_progress',started_at=coalesce(started_at,clock_timestamp()),updated_at=clock_timestamp() where id=p_patient and status='assigned';
  if not found then raise exception '배정된 환자가 아닙니다'; end if;
end $$;


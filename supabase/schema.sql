    update public.rooms set manual_active=false,manual_video_ids='{}',manual_updated_at=clock_timestamp(),session_tags='{}',session_started_at=null,session_age_group=null,session_gender=null,session_treatment=null
    where manual_active or session_started_at is not null;
  end if;
end $$;

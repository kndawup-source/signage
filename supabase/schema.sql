create table if not exists public.pin_accounts (
  id bigint generated by default as identity primary key,
  role text not null unique check (role in ('admin','staff')),
  pin_hash text not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pin_sessions (
  id uuid primary key default gen_random_uuid(),
  account_id bigint not null references public.pin_accounts(id) on delete cascade,
  token_hash bytea not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists pin_sessions_expiry_idx on public.pin_sessions(expires_at);

create table if not exists public.pin_login_throttle (
  client_id text primary key,
  failed_count int not null default 0,
  locked_until timestamptz,
  updated_at timestamptz not null default now()
);

create or replace function public.pin_request_token()
returns text language sql stable security definer set search_path=public as $$
  select nullif((coalesce(nullif(current_setting('request.headers',true),''),'{}')::jsonb ->> 'x-signage-session'),'');
$$;

create or replace function public.pin_session_role()
returns text language sql stable security definer set search_path=public,extensions as $$
  select a.role
  from public.pin_sessions s
  join public.pin_accounts a on a.id=s.account_id and a.enabled
  where s.token_hash=digest(coalesce(public.pin_request_token(),''),'sha256')
    and s.expires_at>clock_timestamp()
  limit 1;
$$;

create or replace function public.is_member()
returns boolean language sql stable security definer set search_path=public as $$
  select public.pin_session_role() in ('admin','staff');
$$;
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select public.pin_session_role()='admin';
$$;

-- SQL Editor에서만 실행: select public.configure_signage_pins('관리자6자리','스텝4~6자리');
create or replace function public.configure_signage_pins(p_admin_pin text,p_staff_pin text)
returns void language plpgsql security definer set search_path=public,extensions as $$
begin
  if p_admin_pin !~ '^[0-9]{6}$' then raise exception 'admin PIN must be exactly 6 digits'; end if;
  if p_staff_pin !~ '^[0-9]{4,6}$' then raise exception 'staff PIN must be 4 to 6 digits'; end if;
  if p_admin_pin=p_staff_pin then raise exception 'admin and staff PIN must differ'; end if;

  insert into public.pin_accounts(role,pin_hash,enabled,updated_at)
  values('admin',crypt(p_admin_pin,gen_salt('bf',10)),true,clock_timestamp())
  on conflict(role) do update set pin_hash=excluded.pin_hash,enabled=true,updated_at=clock_timestamp();

  insert into public.pin_accounts(role,pin_hash,enabled,updated_at)
  values('staff',crypt(p_staff_pin,gen_salt('bf',10)),true,clock_timestamp())
  on conflict(role) do update set pin_hash=excluded.pin_hash,enabled=true,updated_at=clock_timestamp();

  delete from public.pin_sessions;
  delete from public.pin_login_throttle;
end $$;
revoke all on function public.configure_signage_pins(text,text) from public,anon,authenticated;

create or replace function public.pin_login(p_pin text,p_client_id text)
returns jsonb language plpgsql security definer set search_path=public,extensions as $$
declare
  v_client text:=left(trim(coalesce(p_client_id,'')),100);
  v_fail int:=0; v_locked timestamptz; v_account public.pin_accounts; v_token text; v_exp timestamptz;
begin
  if v_client='' or v_client !~ '^[A-Za-z0-9._:-]{8,100}$' then return jsonb_build_object('ok',false,'error','invalid_client'); end if;
  if p_pin !~ '^[0-9]{4,6}$' then return jsonb_build_object('ok',false,'error','invalid_pin'); end if;

  select failed_count,locked_until into v_fail,v_locked from public.pin_login_throttle where client_id=v_client;
  if v_locked is not null and v_locked>clock_timestamp() then
    return jsonb_build_object('ok',false,'error','locked','retry_after_sec',greatest(1,ceil(extract(epoch from (v_locked-clock_timestamp())))::int));
  end if;

  select a.* into v_account
  from public.pin_accounts a
  where a.enabled and crypt(p_pin,a.pin_hash)=a.pin_hash
  order by case a.role when 'admin' then 0 else 1 end
  limit 1;

  if not found then
    v_fail:=coalesce(v_fail,0)+1;
    if v_fail>=5 then
      insert into public.pin_login_throttle(client_id,failed_count,locked_until,updated_at)
      values(v_client,0,clock_timestamp()+interval '5 minutes',clock_timestamp())
      on conflict(client_id) do update set failed_count=0,locked_until=excluded.locked_until,updated_at=clock_timestamp();
      return jsonb_build_object('ok',false,'error','locked','retry_after_sec',300);
    else
      insert into public.pin_login_throttle(client_id,failed_count,locked_until,updated_at)
      values(v_client,v_fail,null,clock_timestamp())
      on conflict(client_id) do update set failed_count=excluded.failed_count,locked_until=null,updated_at=clock_timestamp();
      return jsonb_build_object('ok',false,'error','invalid_pin');
    end if;
  end if;

  delete from public.pin_login_throttle where client_id=v_client;
  delete from public.pin_sessions where expires_at<=clock_timestamp();
  v_token:=encode(gen_random_bytes(32),'hex');
  v_exp:=clock_timestamp()+interval '12 hours';
  insert into public.pin_sessions(account_id,token_hash,expires_at) values(v_account.id,digest(v_token,'sha256'),v_exp);
  return jsonb_build_object('ok',true,'token',v_token,'role',v_account.role,'expires_at',v_exp);
end $$;

create or replace function public.pin_session_info()
returns jsonb language plpgsql stable security definer set search_path=public,extensions as $$
declare v_role text; v_exp timestamptz;
begin
  select a.role,s.expires_at into v_role,v_exp
  from public.pin_sessions s join public.pin_accounts a on a.id=s.account_id and a.enabled
  where s.token_hash=digest(coalesce(public.pin_request_token(),''),'sha256') and s.expires_at>clock_timestamp()
  limit 1;
  if v_role is null then return jsonb_build_object('valid',false); end if;
  return jsonb_build_object('valid',true,'role',v_role,'expires_at',v_exp);
end $$;

create or replace function public.pin_logout()
returns void language plpgsql security definer set search_path=public,extensions as $$
begin
  delete from public.pin_sessions where token_hash=digest(coalesce(public.pin_request_token(),''),'sha256');
end $$;


create or replace function public.admin_change_pin(p_role text,p_pin text)
returns void language plpgsql security definer set search_path=public as $$
declare v_account bigint;
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  if p_role not in ('admin','staff') then raise exception 'invalid role'; end if;
  if p_role='admin' and p_pin !~ '^[0-9]{6}$' then raise exception '관리자 PIN은 숫자 6자리여야 합니다'; end if;
  if p_role='staff' and p_pin !~ '^[0-9]{4,6}$' then raise exception '스텝 PIN은 숫자 4~6자리여야 합니다'; end if;
  if exists(select 1 from public.pin_accounts a where a.role<>p_role and a.enabled and crypt(p_pin,a.pin_hash)=a.pin_hash) then
    raise exception '관리자와 스텝 PIN은 서로 달라야 합니다';
  end if;
  insert into public.pin_accounts(role,pin_hash,enabled,updated_at)
  values(p_role,crypt(p_pin,gen_salt('bf',10)),true,clock_timestamp())
  on conflict(role) do update set pin_hash=excluded.pin_hash,enabled=true,updated_at=clock_timestamp()
  returning id into v_account;
  delete from public.pin_sessions where account_id=v_account;
end $$;
revoke all on function public.admin_change_pin(text,text) from public;
grant execute on function public.admin_change_pin(text,text) to anon,authenticated;


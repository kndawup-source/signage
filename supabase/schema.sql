create or replace function public.admin_create_schedule(p_scope_type text,p_group uuid,p_video_ids uuid[],p_notice text,p_starts_at timestamptz,p_ends_at timestamptz)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_id uuid; v_ids uuid[]; v_label text;
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  if p_scope_type not in ('hospital','group') then raise exception 'invalid scope'; end if;
  if p_ends_at<=p_starts_at then raise exception '종료시각은 시작시각 이후여야 합니다'; end if;
  if p_scope_type='group' and p_group is null then raise exception 'group required'; end if;
  select coalesce(array_agg(v.id order by array_position(p_video_ids,v.id)),'{}'::uuid[]) into v_ids from public.videos v
  where v.id=any(coalesce(p_video_ids,'{}'::uuid[])) and v.active and (v.source<>'local' or v.available);
  if coalesce(array_length(v_ids,1),0)=0 then raise exception 'video required'; end if;
  if p_scope_type='group' then select name into v_label from public.signage_groups where id=p_group; else v_label:='전체 병원'; end if;

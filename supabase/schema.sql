create or replace function public.admin_create_schedule(p_scope_type text,p_group uuid,p_video_ids uuid[],p_notice text,p_starts_at timestamptz,p_ends_at timestamptz)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_id uuid; v_ids uuid[]; v_label text;
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  if p_scope_type not in ('hospital','group') then raise exception 'invalid scope'; end if;
  if p_ends_at<=p_starts_at then raise exception '종료시각은 시작시각 이후여야 합니다'; end if;
  if p_scope_type='group' and p_group is null then raise exception 'group required'; end if;
  select coalesce(array_agg(v.id order by array_position(p_video_ids,v.id)),'{}'::uuid[]) into v_ids from public.videos v
  where v.id=any(coalesce(p_video_ids,'{}'::uuid[])) and v.active and (v.source<>'local' or v.available);
  if coalesce(array_length(v_ids,1),0)=0 then raise exception 'video required'; end if;
  if p_scope_type='group' then select name into v_label from public.signage_groups where id=p_group; else v_label:='전체 병원'; end if;
  insert into public.broadcast_schedules(scope_type,group_id,video_ids,notice_text,starts_at,ends_at)
  values(p_scope_type,case when p_scope_type='group' then p_group else null end,v_ids,nullif(trim(coalesce(p_notice,'')),''),p_starts_at,p_ends_at) returning id into v_id;
  insert into public.control_history(scope_type,scope_id,action,label,after_state) values('schedule',v_id,'schedule_create',v_label,(select to_jsonb(s) from public.broadcast_schedules s where id=v_id));
  return v_id;
end $$;

create or replace function public.admin_delete_schedule(p_id uuid)
returns void language plpgsql security definer set search_path=public as $$
declare v_before jsonb; v_label text;
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  select to_jsonb(s),case when s.scope_type='hospital' then '전체 병원' else coalesce(g.name,'그룹') end into v_before,v_label
  from public.broadcast_schedules s left join public.signage_groups g on g.id=s.group_id where s.id=p_id;
  delete from public.broadcast_schedules where id=p_id;
  if v_before is not null then insert into public.control_history(scope_type,scope_id,action,label,before_state) values('schedule',p_id,'schedule_delete',v_label,v_before); end if;
end $$;

create or replace function public.admin_undo_control(p_history bigint)
returns void language plpgsql security definer set search_path=public as $$
declare h public.control_history; item jsonb;
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  select * into h from public.control_history where id=p_history;
  if not found or h.before_state is null then raise exception '복귀할 상태가 없습니다'; end if;
  if h.scope_type='hospital' then
    update public.broadcast set active=coalesce((h.before_state->>'active')::boolean,false),video_ids=coalesce(ARRAY(SELECT (jsonb_array_elements_text(h.before_state->'video_ids'))::uuid),'{}'::uuid[]),notice_text=h.before_state->>'notice_text',effective_at=null,revision=revision+1,updated_at=clock_timestamp() where id=1;
  elsif h.scope_type='group' then
    insert into public.group_broadcasts(group_id) values(h.scope_id) on conflict(group_id) do nothing;
    update public.group_broadcasts set active=coalesce((h.before_state->>'active')::boolean,false),video_ids=coalesce(ARRAY(SELECT (jsonb_array_elements_text(h.before_state->'video_ids'))::uuid),'{}'::uuid[]),notice_text=h.before_state->>'notice_text',effective_at=null,revision=revision+1,updated_at=clock_timestamp() where group_id=h.scope_id;
  elsif h.scope_type='rooms' then
    for item in select * from jsonb_array_elements(h.before_state) loop
      update public.rooms set manual_active=coalesce((item->>'manual_active')::boolean,false),manual_video_ids=coalesce(ARRAY(SELECT (jsonb_array_elements_text(item->'manual_video_ids'))::uuid),'{}'::uuid[]),manual_updated_at=clock_timestamp() where id=(item->>'id')::uuid;
    end loop;
  else raise exception '이 이력은 직접 복귀할 수 없습니다'; end if;
  insert into public.control_history(scope_type,scope_id,action,label,before_state,after_state) values(h.scope_type,h.scope_id,'undo',coalesce(h.label,'직전 상태'),h.after_state,h.before_state);
end $$;


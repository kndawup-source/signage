create or replace function public.admin_set_group_broadcast(p_group uuid,p_active boolean,p_video_ids uuid[],p_notice text default null,p_delay_ms int default 2000)
returns void language plpgsql security definer set search_path=public as $$
declare v_ids uuid[]; v_before jsonb; v_after jsonb; v_label text;
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  select name into v_label from public.signage_groups where id=p_group;
  if v_label is null then raise exception 'group not found'; end if;
  insert into public.group_broadcasts(group_id) values(p_group) on conflict(group_id) do nothing;
  select to_jsonb(g) into v_before from public.group_broadcasts g where group_id=p_group;
  if coalesce(p_active,false) then
    select coalesce(array_agg(v.id order by array_position(p_video_ids,v.id)),'{}'::uuid[]) into v_ids
    from public.videos v where v.id=any(coalesce(p_video_ids,'{}'::uuid[])) and v.active and (v.source<>'local' or v.available);
  else v_ids:=coalesce(p_video_ids,'{}'::uuid[]); end if;
  update public.group_broadcasts set
    active=coalesce(p_active,false) and coalesce(array_length(v_ids,1),0)>0,
    video_ids=v_ids,notice_text=nullif(trim(coalesce(p_notice,'')),''),
    effective_at=case when coalesce(p_active,false) and coalesce(array_length(v_ids,1),0)>0 then clock_timestamp()+make_interval(secs=>greatest(0,least(coalesce(p_delay_ms,2000),10000))/1000.0) else null end,
    revision=revision+1,updated_at=clock_timestamp() where group_id=p_group;
  select to_jsonb(g) into v_after from public.group_broadcasts g where group_id=p_group;
  insert into public.control_history(scope_type,scope_id,action,label,before_state,after_state) values('group',p_group,case when p_active then 'start' else 'stop' end,v_label,v_before,v_after);
end $$;


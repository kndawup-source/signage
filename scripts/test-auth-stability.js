'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const sql=fs.readFileSync('supabase/v2.36.8-auth-stability.sql','utf8');
assert(fs.readFileSync('supabase/schema.sql','utf8').endsWith(sql));
